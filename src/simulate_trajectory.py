import os
import sys
import argparse

# Ensure Python can find our core modules
sys.path.append(os.path.dirname(os.path.abspath(__file__)))
from core.physics import TrajectorySimulator

def main():
    parser = argparse.ArgumentParser(description="Run the physics backtracking pipeline.")
    parser.add_argument('--image', type=str, default='ow-0004.jpg', help='The satellite image name (e.g. ow-0004.jpg)')
    args = parser.parse_args()

    print("=========================================")
    print(" PHASE 4: OPENDRIFT BACKTRACKING PHYSICS")
    print("=========================================")
    
    base_dir = os.path.dirname(os.path.abspath(__file__))
    tab_file = os.path.abspath(os.path.join(base_dir, '../data/DARTIS/DARTIS_2019.tab'))
    
    # We dynamically find the GeoJSON polygon generated by OpenCV for this image
    geojson_name = args.image.replace('.jpg', '.geojson')
    geojson_path = os.path.abspath(os.path.join(base_dir, f'../{geojson_name}'))
    
    if not os.path.exists(geojson_path):
        print(f"[!] Error: {geojson_path} does not exist. Please run Phase 3 (OpenCV extraction) first.")
        return

    print(f"[*] Booting Trajectory Simulator for {args.image}...")
    simulator = TrajectorySimulator(tab_file)
    
    # Run the backtrack simulation for exactly 48 hours as per industry standard
    simulator.run_backtrack(geojson_path, args.image, hours_to_backtrack=48)

if __name__ == '__main__':
    main()
